#!/usr/bin/env node
// Generate bridge nested-call validation constraints from the canonical MCP schemas.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { register } from "node:module";
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MCP_SERVER = resolve(REPO_ROOT, "mcp-server");
const LOADER_SOURCE = `
export async function resolve(specifier, context, nextResolve) {
  if (
    specifier.endsWith(".js") &&
    !specifier.startsWith("node:") &&
    !specifier.includes("node_modules") &&
    !specifier.startsWith("@")
  ) {
    const tsSpec = specifier.slice(0, -3) + ".ts";
    try {
      return await nextResolve(tsSpec, context);
    } catch {
      // fall through to default resolve
    }
  }
  return nextResolve(specifier, context);
}
`;
register(`data:text/javascript,${encodeURIComponent(LOADER_SOURCE)}`, import.meta.url);

const { ALL_TOOLS } = await import(
  resolve(MCP_SERVER, "src/tools/index.ts")
);

function constraints(schema) {
  const result = {};
  for (const [key, value] of Object.entries(schema)) {
    if (["type", "required", "enum", "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "minItems", "maxItems", "minLength", "maxLength", "pattern", "additionalProperties"].includes(key)) result[key] = value;
    else if (key === "properties") result[key] = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, constraints(v)]));
    else if (key === "items") result[key] = constraints(value);
    else if (["anyOf", "oneOf", "allOf"].includes(key)) result[key] = value.map(constraints);
  }
  return result;
}
const rows = ALL_TOOLS.map(t => `            { "${t.name}", @"${JSON.stringify(constraints(t.inputSchema)).replaceAll('"', '""')}" },`);
const content = '// Generated by scripts/generate-batch-schemas.mjs. Do not edit.\nusing System.Collections.Generic;\nnamespace UnityOpenMcpBridge\n{\n    internal static class BridgeBatchSchemas\n    {\n        internal static readonly Dictionary<string, string> ByTool = new Dictionary<string, string>\n        {\n' + rows.join('\n') + '\n        };\n    }\n}\n';
const target = resolve(REPO_ROOT, 'packages/bridge/Editor/Bridge/BridgeBatchSchemas.cs');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== content) throw new Error('Bridge batch schemas are stale. Run node scripts/generate-batch-schemas.mjs');
} else writeFileSync(target, content);
